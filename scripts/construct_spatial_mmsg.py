import os
import json
import random
from PIL import Image
from tqdm import tqdm

CODE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
THESIS_DIR = os.path.dirname(CODE_DIR)

DATASET_DIR = os.path.join(THESIS_DIR, 'Dataset', 'VRD', 'vrd')
OUTPUT_DIR = os.path.join(CODE_DIR, 'data', 'Spatial-VRD')

RGB_OUT = os.path.join(OUTPUT_DIR, 'images_rgb')
DEPTH_OUT = os.path.join(OUTPUT_DIR, 'images_depth')

def parse_split(json_name, img_folder, depth_folder, split_name, entity2id, relation2id, entity2text, triplets):
    json_path = os.path.join(DATASET_DIR, json_name)
    if not os.path.exists(json_path):
        print(f"File not found: {json_path}")
        return
        
    with open(json_path, 'r', encoding='utf-8') as f:
        data = json.load(f)
        
    if isinstance(data, dict):
        # some versions of VRD use dict instead of list
        data = [{'filename': k, **v} for k, v in data.items()]
        
    print(f"Processing {split_name} split with {len(data)} images...")
    
    img_dir = os.path.join(DATASET_DIR, img_folder)
    depth_dir = os.path.join(DATASET_DIR, depth_folder)
    
    for img_data in tqdm(data, desc=f"Cropping {split_name}"):
        filename = img_data.get('filename')
        photo_id = str(img_data.get('photo_id', os.path.splitext(filename)[0]))
        
        rgb_path = os.path.join(img_dir, filename)
        # depth map generated by depth estimation model
        depth_path = os.path.join(depth_dir, os.path.splitext(filename)[0] + '.png')
        
        if not os.path.exists(rgb_path) or not os.path.exists(depth_path):
            continue # skip if images are missing
            
        rgb_img = None
        depth_img = None
        
        objects = img_data.get('objects', [])
        for obj_idx, obj in enumerate(objects):
            if 'bbox' not in obj:
                continue
                
            eid = f"{photo_id}_{obj_idx}"
            
            if eid not in entity2id:
                entity2id[eid] = len(entity2id)
                
            if eid not in entity2text:
                attrs = obj.get('attributes', [])
                if isinstance(attrs, str):
                    attrs = [attrs]
                names = obj.get('names', obj.get('name', 'object'))
                if isinstance(names, list):
                    name_str = " ".join(names)
                else:
                    name_str = str(names)
                obj_text = (" ".join(attrs) + " " + name_str).strip()
                entity2text[eid] = obj_text if obj_text else "object"
                
            # Check if cropped images already exist
            out_rgb_path = os.path.join(RGB_OUT, f"{eid}.jpg")
            out_depth_path = os.path.join(DEPTH_OUT, f"{eid}.png")
            
            if not os.path.exists(out_rgb_path) or not os.path.exists(out_depth_path):
                if rgb_img is None:
                    rgb_img = Image.open(rgb_path).convert('RGB')
                    depth_img = Image.open(depth_path) # grayscale/uint16
                    
                bbox = obj['bbox']
                if 'w' in bbox and 'h' in bbox:
                    x, y, w, h = bbox['x'], bbox['y'], bbox['w'], bbox['h']
                    crop_box = (x, y, x+w, y+h)
                else:
                    crop_box = (bbox['xmin'], bbox['ymin'], bbox['xmax'], bbox['ymax'])
                
                # prevent out of bounds
                crop_box = (
                    max(0, crop_box[0]), 
                    max(0, crop_box[1]),
                    min(rgb_img.width, crop_box[2]),
                    min(rgb_img.height, crop_box[3])
                )
                
                try:
                    c_rgb = rgb_img.crop(crop_box)
                    c_rgb.save(out_rgb_path)
                    
                    c_depth = depth_img.crop(crop_box)
                    c_depth.save(out_depth_path)
                except Exception as e:
                    pass
                    
        # Extract relations
        rels = img_data.get('relationships', [])
        for rel in rels:
            if 'objects' not in rel or len(rel['objects']) != 2:
                continue
            subj_idx, obj_idx = rel['objects']
            pred = rel.get('relationship', 'unknown')
            
            subj_eid = f"{photo_id}_{subj_idx}"
            obj_eid = f"{photo_id}_{obj_idx}"
            
            if subj_eid in entity2id and obj_eid in entity2id:
                if pred not in relation2id:
                    relation2id[pred] = len(relation2id)
                # Store triplet in standard format: (head, relation, tail)
                triplets.append((subj_eid, pred, obj_eid))


def main():
    os.makedirs(RGB_OUT, exist_ok=True)
    os.makedirs(DEPTH_OUT, exist_ok=True)
    
    entity2id = {}
    relation2id = {}
    entity2text = {}
    train_triplets = []
    test_triplets = []
    
    # Process Train Split
    parse_split(
        'sg_train_annotations.json', 'sg_train_images', 'sg_train_depths', 
        'Train', entity2id, relation2id, entity2text, train_triplets
    )
    
    # Process Test Split
    parse_split(
        'sg_test_annotations.json', 'sg_test_images', 'sg_test_depths', 
        'Test', entity2id, relation2id, entity2text, test_triplets
    )
    
    # Split Train triplets into Train (90%) and Valid (10%)
    random.seed(42)
    random.shuffle(train_triplets)
    split_idx = int(0.9 * len(train_triplets))
    actual_train = train_triplets[:split_idx]
    actual_valid = train_triplets[split_idx:]
    
    # 1. Save Entity & Relation Mappings
    with open(os.path.join(OUTPUT_DIR, 'entity2id.txt'), 'w', encoding='utf-8') as f:
        f.write(f"{len(entity2id)}\n")
        for e, idx in entity2id.items():
            f.write(f"{e}\t{idx}\n")
            
    with open(os.path.join(OUTPUT_DIR, 'relation2id.txt'), 'w', encoding='utf-8') as f:
        f.write(f"{len(relation2id)}\n")
        for r, idx in relation2id.items():
            f.write(f"{r}\t{idx}\n")
            
    # 2. Save Entity Text (for RoBERTa / BERT Text Encoder)
    with open(os.path.join(OUTPUT_DIR, 'entity2text.txt'), 'w', encoding='utf-8') as f:
        for e, text in entity2text.items():
            f.write(f"{e}\t{text}\n")
            
    # 3. Save Triplets in standard format: Head -> Relation -> Tail (s \t p \t o)
    with open(os.path.join(OUTPUT_DIR, 'train.txt'), 'w', encoding='utf-8') as f:
        f.write(f"{len(actual_train)}\n")
        for s, p, o in actual_train:
            f.write(f"{s}\t{p}\t{o}\n")
            
    with open(os.path.join(OUTPUT_DIR, 'valid.txt'), 'w', encoding='utf-8') as f:
        f.write(f"{len(actual_valid)}\n")
        for s, p, o in actual_valid:
            f.write(f"{s}\t{p}\t{o}\n")
            
    with open(os.path.join(OUTPUT_DIR, 'test.txt'), 'w', encoding='utf-8') as f:
        f.write(f"{len(test_triplets)}\n")
        for s, p, o in test_triplets:
            f.write(f"{s}\t{p}\t{o}\n")
            
    print(f"\nDone! Extracted {len(entity2id)} entities, {len(relation2id)} relations, {len(entity2text)} entity descriptions.")
    print(f"Train Triplets: {len(actual_train)}")
    print(f"Valid Triplets: {len(actual_valid)}")
    print(f"Test Triplets:  {len(test_triplets)}")

if __name__ == '__main__':
    main()
